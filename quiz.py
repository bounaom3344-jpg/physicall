MIX_LABEL = "ທົດສອບລວມ (ສຸ່ມ 10 ຂໍ້)"


def _render(key, questions):
    """ແຕ້ມແບບທົດສອບ: ຟອມຄຳຖາມ → ສົ່ງຄຳຕອບ → ສະແດງຄະແນນ ແລະ ເຉລີຍ"""
    ver_key = f"{key}_ver"
    ver = st.session_state.get(ver_key, 0)

    with st.form(f"form_{key}_{ver}"):
        picks = []
        for i, q in enumerate(questions):
            st.markdown(f"**ຂໍ້ {i + 1}.** {q['q']}")
            picks.append(
                st.radio("ເລືອກຄຳຕອບ", q["options"], index=None,
                         key=f"{key}_{ver}_{i}", label_visibility="collapsed")
            )
            st.write("")
        sent = st.form_submit_button("📤 ສົ່ງຄຳຕອບ", type="primary")

    if sent:
        results = []
        for q, p in zip(questions, picks):
            results.append(p == q["options"][q["answer"]])
        score = sum(results)
        total = len(questions)
        pct = 100 * score / total
        st.subheader("ຜົນການທົດສອບ")
        c1, c2 = st.columns(2)
        c1.metric("ຄະແນນ", f"{score} / {total}")
        c2.metric("ເປີເຊັນ", f"{pct:.0f} %")
        if pct >= 80:
            st.success("ດີເລີດ! 🎉")
        elif pct >= 50:
            st.info("ພໍໃຊ້ ລອງທົບທວນບົດຮຽນອີກຄັ້ງ")
        else:
            st.warning("ຄວນທົບທວນບົດຮຽນ ແລ້ວລອງໃໝ່ອີກຄັ້ງ")

        for i, (q, p, ok) in enumerate(zip(questions, picks, results)):
            correct = q["options"][q["answer"]]
            icon = "✅" if ok else ("⚪" if p is None else "❌")
            with st.expander(f"{icon} ຂໍ້ {i + 1}", expanded=not ok):
                st.markdown(q["q"])
                if p is None:
                    st.write("ບໍ່ໄດ້ຕອບ")
                elif not ok:
                    st.write(f"ຄຳຕອບຂອງທ່ານ: {p}")
                st.write(f"ຄຳຕອບທີ່ຖືກ: **{correct}**")
                st.caption(q["explain"])

    if st.button("🔄 ເຮັດໃໝ່", key=f"{key}_reset_{ver}"):
        st.session_state[ver_key] = ver + 1
        st.session_state.pop(f"{key}_sample", None)
        st.rerun()


def main():
    st.header("📝 ແບບທົດສອບຟີຊິກ")
    topic = st.sidebar.selectbox("ເລືອກຊຸດຂໍ້ສອບ", list(QUESTIONS.keys()) + [MIX_LABEL])

    if topic == MIX_LABEL:
        pool = [q for qs in QUESTIONS.values() for q in qs]
        ver = st.session_state.get("mix_ver", 0)
        sample = st.session_state.get("mix_sample")
        if sample is None or st.session_state.get("mix_sample_ver") != ver:
            sample = random.sample(pool, min(10, len(pool)))
            st.session_state["mix_sample"] = sample
            st.session_state["mix_sample_ver"] = ver
        st.caption("ສຸ່ມຈາກທຸກຫົວຂໍ້: ການເຄື່ອນທີ່ຊື່, ແຮງ, ງານ, ພະລັງງານ, ແສງສະຫວ່າງ")
        _render("mix", sample)
    else:
        st.caption(f"ຫົວຂໍ້: {topic} — {len(QUESTIONS[topic])} ຂໍ້")
        _render(f"quiz_{topic}", QUESTIONS[topic])
